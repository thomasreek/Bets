"""Bet log: record bets, settle them (by hand or from final scores), and report profit."""

from __future__ import annotations

import csv
from dataclasses import asdict, dataclass, fields
from datetime import datetime, timezone
from pathlib import Path

from .odds_math import decimal_to_american

REPO_ROOT = Path(__file__).resolve().parent.parent
LOG_FILE = REPO_ROOT / "bet_log.csv"
TABLE_FILE = REPO_ROOT / "BETS.md"

STATUSES = ("open", "won", "lost", "push", "void")


@dataclass
class Bet:
    id: int
    placed: str  # date placed, YYYY-MM-DD
    sport: str  # Odds API sport key, used for automatic settling
    event: str  # "Away @ Home"
    selection: str
    book: str
    stake: float
    odds: float  # decimal
    fair_odds: float | None  # fair price when placed, for expected value
    start: str  # game start, ISO 8601 UTC
    status: str = "open"
    notes: str = ""

    @property
    def to_win(self) -> float:
        return round(self.stake * (self.odds - 1), 2)

    @property
    def profit(self) -> float:
        if self.status == "won":
            return self.to_win
        if self.status == "lost":
            return -self.stake
        return 0.0

    @property
    def expected_profit(self) -> float | None:
        if not self.fair_odds:
            return None
        return self.stake * (self.odds / self.fair_odds - 1)


def load(path: Path = LOG_FILE) -> list[Bet]:
    if not path.exists():
        return []
    bets = []
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            bets.append(Bet(
                id=int(row["id"]), placed=row["placed"], sport=row["sport"], event=row["event"],
                selection=row["selection"], book=row["book"], stake=float(row["stake"]),
                odds=float(row["odds"]), fair_odds=float(row["fair_odds"]) if row["fair_odds"] else None,
                start=row["start"], status=row["status"], notes=row.get("notes", ""),
            ))
    return bets


def save(bets: list[Bet], path: Path = LOG_FILE, table: Path | None = TABLE_FILE) -> None:
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=[fl.name for fl in fields(Bet)])
        writer.writeheader()
        for b in bets:
            row = asdict(b)
            row["fair_odds"] = "" if b.fair_odds is None else b.fair_odds
            writer.writerow(row)
    if table:
        table.write_text(render_markdown(bets))


def add(bets: list[Bet], **kw) -> Bet:
    bet = Bet(id=max((b.id for b in bets), default=0) + 1, **kw)
    bets.append(bet)
    return bet


def summary(bets: list[Bet]) -> dict:
    settled = [b for b in bets if b.status in ("won", "lost", "push")]
    graded = [b for b in settled if b.status != "push"]
    staked = sum(b.stake for b in settled)
    profit = sum(b.profit for b in settled)
    ev = [b.expected_profit for b in settled if b.expected_profit is not None]
    return {
        "bets": len(bets),
        "open": sum(b.status == "open" for b in bets),
        "open_stake": sum(b.stake for b in bets if b.status == "open"),
        "won": sum(b.status == "won" for b in bets),
        "lost": sum(b.status == "lost" for b in bets),
        "push": sum(b.status == "push" for b in bets),
        "staked": staked,
        "profit": profit,
        "roi": profit / staked if staked else 0.0,
        "win_rate": sum(b.status == "won" for b in graded) / len(graded) if graded else 0.0,
        "expected_profit": sum(ev),
    }


def _money(x: float) -> str:
    return f"-${abs(x):,.2f}" if x < 0 else f"${x:,.2f}"


def render_markdown(bets: list[Bet]) -> str:
    s = summary(bets)
    lines = [
        "# Bet log",
        "",
        "Generated by `python -m betfinder bet ...`. Edit bets with the commands, not by hand.",
        "",
        "## Summary",
        "",
        "| Bets | Record (W-L-P) | Open | Staked (settled) | Profit | ROI | Expected profit |",
        "|---|---|---|---|---|---|---|",
        f"| {s['bets']} | {s['won']}-{s['lost']}-{s['push']} | {s['open']} ({_money(s['open_stake'])}) "
        f"| {_money(s['staked'])} | **{_money(s['profit'])}** | {s['roi']:.1%} | {_money(s['expected_profit'])} |",
        "",
        "Expected profit is what the bets were worth at the fair price when placed. Over hundreds of bets, "
        "profit should track it. Over a few bets, luck dominates.",
        "",
        "## Bets",
        "",
        "| # | Placed | Event | Bet | Book | Stake | Odds | To win | Edge | Result | Profit |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    icons = {"won": "✅ Won", "lost": "❌ Lost", "push": "↩️ Push", "void": "Void", "open": "⏳ Open"}
    for b in sorted(bets, key=lambda b: b.id, reverse=True):
        edge = f"{b.odds / b.fair_odds - 1:+.1%}" if b.fair_odds else ""
        profit = _money(b.profit) if b.status in ("won", "lost", "push") else ""
        lines.append(
            f"| {b.id} | {b.placed} | {b.event} | {b.selection} | {b.book} | {_money(b.stake)} "
            f"| {b.odds:.3f} ({decimal_to_american(b.odds):+d}) | {_money(b.to_win)} | {edge} "
            f"| {icons.get(b.status, b.status)} | {profit} |"
        )
    return "\n".join(lines) + "\n"


def grade_h2h(selection: str, scores: list[dict]) -> str | None:
    """Grade a moneyline bet from final scores: won, lost, or None if it can't tell."""
    try:
        pts = {s["name"]: float(s["score"]) for s in scores}
    except (KeyError, TypeError, ValueError):
        return None
    if len(pts) != 2:
        return None
    (a, sa), (b, sb) = pts.items()
    if selection == "Draw":
        return "won" if sa == sb else "lost"
    if selection not in pts:
        return None
    if sa == sb:
        return "push"  # two-way market that ended level (e.g. NFL tie)
    winner = a if sa > sb else b
    return "won" if selection == winner else "lost"


def auto_settle(bets: list[Bet], client, now: datetime | None = None) -> list[tuple[Bet, str]]:
    """Settle open moneyline bets whose games are final, using The Odds API scores endpoint."""
    now = now or datetime.now(timezone.utc)
    due = [b for b in bets if b.status == "open" and b.sport and b.start
           and datetime.fromisoformat(b.start.replace("Z", "+00:00")) < now]
    settled = []
    for sport in sorted({b.sport for b in due}):
        games = client.scores(sport, days_from=3)
        for b in (x for x in due if x.sport == sport):
            away, _, home = b.event.partition(" @ ")
            for g in games:
                if g.get("completed") and g.get("home_team") == home and g.get("away_team") == away:
                    is_soccer = sport.startswith("soccer")
                    result = grade_h2h(b.selection, g.get("scores") or [])
                    if result == "push" and is_soccer:
                        result = "lost"  # 3-way market: a draw loses a team bet
                    if result:
                        b.status = result
                        settled.append((b, result))
                    break
    return settled
